"""`nexo ci export github|gitlab|azure|jenkins` (D123): the file of each
CI service. Every step is a job that runs `nexo ci run PIPELINE FILE --step
NAME --yes`; what the steps keep travels in `.nexo/ci` between jobs, a
step that calls approve() waits for the service's own approval, and the
after blocks run when the steps pass or fail."""
from __future__ import annotations

TARGETS = ("github", "gitlab", "azure", "jenkins")
INSTALL = "pip install nexo"


def header(target: str, file: str) -> str:
    return f"Generated by nexo ci export {target} from {file}; do not edit."


def command(p, file: str, step: str | None = None, after: str | None = None) -> str:
    if after is not None:
        return f"nexo ci run {p.name} {file} --after {after}"
    return f"nexo ci run {p.name} {file} --step {step} --yes"


def quote(text: str) -> str:
    """A YAML string in single quotes."""
    return "'" + text.replace("'", "''") + "'"


def export(target: str, p, file: str, approvals: dict) -> tuple[str, str]:
    """(path, text) of the file."""
    return {"github": github, "gitlab": gitlab, "azure": azure, "jenkins": jenkins}[target](p, file, approvals)


def github(p, file, approvals):
    out = [f"# {header('github', file)}", f"name: {p.name}", "on:"]
    if not p.triggers:
        out.append("  workflow_dispatch:")
    for kind, branch in p.triggers:
        if kind == "push":
            out.append("  push:")
            if branch:
                out += ["    branches:", f"      - {quote(branch)}"]
        else:
            out.append("  pull_request:")
    if p.secrets:
        out.append("env:")
        out += [f"  {s}: ${{{{ secrets.{s} }}}}" for s in p.secrets]
    out.append("jobs:")
    names = [s[0] for s in p.steps]

    def job(jid, needs, run, extra=()):
        lines = [f"  {jid}:", "    runs-on: ubuntu-latest"]
        if needs:
            lines.append(f"    needs: [{', '.join(needs)}]")
        lines += list(extra)
        lines += ["    steps:", "      - uses: actions/checkout@v4", "        with:", "          fetch-depth: 0",
                  "      - uses: actions/setup-python@v5", "        with:", "          python-version: '3.12'",
                  f"      - run: {INSTALL}"]
        if needs:
            lines += ["      - uses: actions/download-artifact@v4", "        with:", "          name: nexo-ci",
                      "          path: .nexo/ci"]
        lines.append(f"      - run: {run}")
        return lines

    for i, name in enumerate(names):
        extra = []
        if name in approvals:
            extra = [f"    # approve: {', '.join(approvals[name])}", f"    environment: {name}"]
        lines = job(name, names[i - 1:i], command(p, file, name), extra)
        lines += ["      - uses: actions/upload-artifact@v4", "        if: always()", "        with:",
                  "          name: nexo-ci", "          path: .nexo/ci", "          include-hidden-files: true",
                  "          overwrite: true"]
        out += lines
    for what, cond in (("success", "success()"), ("failure", "failure()")):
        if what in p.after:
            out += job(f"after-{what}", names, command(p, file, after=what), [f"    if: {cond}"])
    return f".github/workflows/{p.name}.yml", "\n".join(out) + "\n"


def gitlab(p, file, approvals):
    names = [s[0] for s in p.steps]
    stages = names + (["after"] if p.after else [])
    out = [f"# {header('gitlab', file)}"]
    if p.secrets:
        out.append(f"# secrets (CI/CD variables): {', '.join(p.secrets)}")
    out += ["workflow:", "  rules:"]
    if not p.triggers:
        out.append('    - if: $CI_PIPELINE_SOURCE == "web"')
    for kind, branch in p.triggers:
        if kind == "push" and branch:
            out.append(f'    - if: $CI_PIPELINE_SOURCE == "push" && $CI_COMMIT_BRANCH == "{branch}"')
        elif kind == "push":
            out.append('    - if: $CI_PIPELINE_SOURCE == "push"')
        else:
            out.append('    - if: $CI_PIPELINE_SOURCE == "merge_request_event"')
    out += ["stages:"] + [f"  - {s}" for s in stages]
    out += ["default:", "  image: python:3.12", "  before_script:", f"    - {INSTALL}", "  artifacts:",
            "    when: always", "    paths:", "      - .nexo/ci/", "variables:", "  GIT_DEPTH: 0"]
    for name in names:
        out += [f"{name}:", f"  stage: {name}"]
        if name in approvals:
            out += [f"  # approve: {', '.join(approvals[name])}", "  when: manual", "  allow_failure: false"]
        out += ["  script:", f"    - {command(p, file, name)}"]
    for what, when in (("success", "on_success"), ("failure", "on_failure")):
        if what in p.after:
            out += [f"after-{what}:", "  stage: after", f"  when: {when}", "  script:",
                    f"    - {command(p, file, after=what)}"]
    return ".gitlab-ci.yml", "\n".join(out) + "\n"


def azure(p, file, approvals):
    out = [f"# {header('azure', file)}"]
    pushes = [b for k, b in p.triggers if k == "push"]
    if pushes:
        out += ["trigger:", "  branches:", "    include:"]
        out += [f"      - {quote(b or '*')}" for b in pushes]
    else:
        out.append("trigger: none")
    if any(k == "pull_request" for k, _ in p.triggers):
        out += ["pr:", "  branches:", "    include:", "      - '*'"]
    else:
        out.append("pr: none")
    out += ["pool:", "  vmImage: ubuntu-latest", "stages:"]
    names = [s[0] for s in p.steps]

    def steps(run, download, publish, stage):
        lines = ["          - checkout: self", "            fetchDepth: 0",
                 "          - task: UsePythonVersion@0", "            inputs:", "              versionSpec: '3.12'",
                 f"          - script: {INSTALL}"]
        # after a failure, the artifact of the last step that ran wins
        for d in download:
            lines += ["          - task: DownloadPipelineArtifact@2"]
            if len(download) > 1:
                lines.append("            continueOnError: true")
            lines += ["            inputs:", f"              artifact: nexo-ci-{d}", "              path: .nexo/ci"]
        lines.append(f"          - script: {run}")
        if p.secrets:
            lines.append("            env:")
            lines += [f"              {s}: $({s})" for s in p.secrets]
        if publish:
            lines += ["          - task: PublishPipelineArtifact@1", "            condition: always()",
                      "            inputs:", "              targetPath: .nexo/ci", f"              artifact: nexo-ci-{stage}"]
        return lines

    for i, name in enumerate(names):
        out += [f"  - stage: {name}"]
        if i:
            out.append(f"    dependsOn: {names[i - 1]}")
        out.append("    jobs:")
        if name in approvals:
            out += ["      - job: approve", "        pool: server", "        steps:",
                    "          - task: ManualValidation@0", "            inputs:",
                    f"              notifyUsers: {quote(', '.join(approvals[name]))}",
                    f"              instructions: {quote('Approve the step ' + name)}"]
        out += [f"      - job: {name}"]
        if name in approvals:
            out.append("        dependsOn: approve")
        out.append("        steps:")
        out += steps(command(p, file, name), names[i - 1:i], True, name)
    for what, cond in (("success", "succeeded()"), ("failure", "failed()")):
        if what in p.after:
            out += [f"  - stage: after_{what}", "    dependsOn:"] + [f"      - {n}" for n in names]
            out += [f"    condition: {cond}", "    jobs:", f"      - job: after_{what}", "        steps:"]
            out += steps(command(p, file, after=what), names if what == "failure" else names[-1:], False, "")
    return "azure-pipelines.yml", "\n".join(out) + "\n"


def jenkins(p, file, approvals):
    def groovy(text):
        return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"

    conds = []
    for kind, branch in p.triggers:
        if kind == "push" and branch:
            conds.append(f"allOf {{ not {{ changeRequest() }}; branch {groovy(branch)} }}")
        elif kind == "push":
            conds.append("not { changeRequest() }")
        else:
            conds.append("changeRequest()")
    out = [f"// {header('jenkins', file)}", "pipeline {", "    agent any"]
    if p.secrets:
        out.append("    environment {")
        out += [f"        {s} = credentials({groovy(s)})" for s in p.secrets]
        out.append("    }")
    out += ["    stages {", "        stage('setup') {", f"            steps {{ sh {groovy(INSTALL)} }}", "        }"]
    for name, _, _ in p.steps:
        out.append(f"        stage({groovy(name)}) {{")
        if conds:
            out.append(f"            when {{ anyOf {{ {'; '.join(conds)} }} }}")
        if name in approvals:
            out.append(f"            input {{ message {groovy('Approve the step ' + name)}; "
                       f"submitter {groovy(','.join(approvals[name]))} }}")
        out += [f"            steps {{ sh {groovy(command(p, file, name))} }}", "        }"]
    out.append("    }")
    if p.after:
        out.append("    post {")
        for what in ("success", "failure"):
            if what in p.after:
                out.append(f"        {what} {{ sh {groovy(command(p, file, after=what))} }}")
        out.append("    }")
    out.append("}")
    return "Jenkinsfile", "\n".join(out) + "\n"
