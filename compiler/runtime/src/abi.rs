/// `obj.name` as a place.
#[no_mangle]
pub unsafe extern "C" fn nx_field_slot(ot: u64, ob: u64, name: *const u8, len: u64, span: u32) -> *mut V {
    let len = len as usize;
    let mut tmp = Val::none();
    match call::field_slot(v(ot, ob), text(name, len), &mut tmp, span) {
        Ok(Some(p)) => p,
        Ok(None) => scratch(tmp),
        Err(_) => scratch(Val::none()),
    }
}

/// `(*slot)[index]` as a place.
#[no_mangle]
pub unsafe extern "C" fn nx_index_slot(slot: *mut V, it: u64, ib: u64, span: u32) -> *mut V {
    let container = crate::cow::make_unique(slot);
    let forced = match pipe::force(container) {
        Ok(f) => f,
        Err(_) => return scratch(Val::none()),
    };
    let mut tmp = Val::none();
    match coll::element_slot(forced.v(), v(it, ib), &mut tmp, span) {
        Ok(Some(p)) => p,
        Ok(None) => scratch(tmp),
        Err(_) => scratch(Val::none()),
    }
}

/// `(*slot)[index] = value`
#[no_mangle]
pub unsafe extern "C" fn nx_set_index_at(slot: *mut V, it: u64, ib: u64, t: u64, b: u64, span: u32) {
    let container = crate::cow::make_unique(slot);
    // `counts[k] = value` with an int key and a value that is not lazy (D134)
    if it == T_INT && t != T_OBJ {
        if let Some(Obj::Map(m)) = container.get() {
            if owners(container) <= 1 {
                m.borrow_mut().insert(Key::Int(ib as i64), Val::int(ib as i64), Val::from(v(t, b).plain()));
                scratch_clear();
                return;
            }
        }
    }
    let _ = coll::set_index(container, v(it, ib), v(t, b), span);
    scratch_clear();
}

