static TESTS: Mutex<Vec<(String, Val)>> = Mutex::new(Vec::new());

/// A `test` block reached while running the top level of the file.
#[no_mangle]
pub unsafe extern "C" fn nx_test_register(name: *const u8, len: u64, t: u64, b: u64) {
    let len = len as usize;
    let name = text(name, len).to_string();
    TESTS.lock().unwrap().push((name, Val::from(v(t, b))));
}

/// Run every registered test, each in its own scope (D54).
#[no_mangle]
pub extern "C" fn nx_run_tests() -> ! {
    let tests: Vec<(String, Val)> = TESTS.lock().unwrap().clone();
    if !tests.is_empty() {
        if !crate::web::serve_in_background() {
            state::report_pending();
            std::process::exit(1);
        }
        nx_test_header();
    }
    for (name, f) in tests {
        crate::library::clear_fakes();
        crate::stream::reset_memory();
        let r = call::call_value(f.v(), &[], 0);
        if r.is_ok() {
            crate::stream::drain();
        }
        drop(r);
        crate::library::clear_fakes();
        unsafe { nx_test_result(name.as_ptr(), name.len() as u64) };
    }
    nx_test_finish()
}

/// `nexo test`: a message sent is delivered at once (D117).
#[no_mangle]
pub extern "C" fn nx_stream_test_mode() {
    crate::stream::set_test_mode();
}

