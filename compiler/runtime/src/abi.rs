/// After a test block: ✓ or ✗ and the failure.
#[no_mangle]
pub unsafe extern "C" fn nx_test_result(name: *const u8, len: u64) {
    let len = len as usize;
    let mut counts = TEST_COUNTS.lock().unwrap();
    counts.0 += 1;
    if state::failing() != 0 {
        state::write_out(&format!("✗ {}\n", text(name, len)));
        state::report_pending();
        state::clear();
    } else {
        counts.1 += 1;
        state::write_out(&format!("✓ {}\n", text(name, len)));
        state::flush();
    }
}

/// End of `nexo test` for this file: tell the driver how many tests ran.
#[no_mangle]
pub extern "C" fn nx_test_finish() -> ! {
    let (run, passed) = *TEST_COUNTS.lock().unwrap();
    if let Ok(path) = std::env::var("NEXO_TEST_REPORT") {
        let _ = std::fs::write(path, format!("{run} {passed}\n"));
    }
    crate::library::write_coverage();
    // a mistake in a handler of a server is a broken program (D102)
    nx_exit(if crate::web::MISTAKE.load(std::sync::atomic::Ordering::SeqCst) { 1 } else { 0 })
}

static TEST_COUNTS: Mutex<(u32, u32)> = Mutex::new((0, 0));

