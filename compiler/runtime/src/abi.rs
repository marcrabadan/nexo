#[no_mangle]
pub unsafe extern "C" fn nx_list(items: *const V, n: u64) -> V {
    let mut out = Vec::with_capacity(n as usize);
    for x in values(items, n) {
        match pipe::bind(*x) {
            Ok(b) => out.push(b),
            Err(_) => return NONE,
        }
    }
    list(out).into_raw()
}

