#[no_mangle]
pub unsafe extern "C" fn nx_init(
    file: *const u8,
    file_len: u64,
    src: *const u8,
    src_len: u64,
    spans: *const SpanRec,
    nspans: u64,
    cleanup: extern "C" fn(*mut Tls),
) {
    let file_len = file_len as usize;
    let src_len = src_len as usize;
    if std::env::var("NEXO_LEAKCHECK").is_ok_and(|v| v == "1") {
        enable_leakcheck();
    }
    *CLEANUP.lock().unwrap() = Some(cleanup);
    find_field_offset();
    let spans: &'static [SpanRec] = if nspans == 0 { &[] } else { std::slice::from_raw_parts(spans, nspans as usize) };
    state::init(text(file, file_len), text(src, src_len), spans);
}

