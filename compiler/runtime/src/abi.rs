/// An int-only function was entered with its depth over the thread's
/// limit: too many nested calls, or a `try within` whose clock to check.
#[no_mangle]
pub extern "C" fn nx_enter_slow(depth: u64) {
    // a failure is on its way: the function returns at once (D177)
    if state::failing() != 0 {
        return;
    }
    if depth > state::MAX_DEPTH {
        nx_too_deep();
    } else {
        nx_check_deadline();
    }
}

/// The slow path of a pure int function (D179): the depth goes to the
/// thread state here, and the answer says whether the function fails.
#[no_mangle]
pub extern "C" fn nx_enter_slow_pure(depth: u64) -> u8 {
    state::set_depth(depth);
    nx_enter_slow(depth);
    state::failing()
}

#[no_mangle]
pub extern "C" fn nx_exit(code: i32) -> ! {
    // the program ends when every spawned task has ended
    crate::sync::wait_all();
    // then its servers answer and its streams are read until it is
    // stopped (D102, D117)
    let mut code = code;
    if code == 0 && crate::stream::memory_profile() {
        crate::stream::drain();
        if state::failing() != 0 { state::report_pending(); code = 1; }
        crate::sync::wait_all();
    }
    if code == 0 && crate::stream::listening() && !crate::stream::in_test_mode() {
        let file = state::program().file.to_string();
        if !crate::web::has_servers() {
            crate::stream::listen_forever(&file);
        }
        crate::value::going_multi();
        std::thread::spawn(move || crate::stream::listen_forever(&file));
    }
    if code == 0 && !crate::web::serve_forever() {
        code = 1;
    }
    if crate::security::ingress::port().is_some() { crate::sync::wait_all(); }
    if leakcheck_enabled() {
        check_leaks();
    }
    state::flush();
    std::process::exit(code)
}

/// NEXO_LEAKCHECK=1: release everything the program still holds and
/// report the objects that were not freed (section 25, phase 2).
fn check_leaks() {
    if let Some(f) = *CLEANUP.lock().unwrap() {
        f(state::tls());
    }
    TESTS.lock().unwrap().clear();
    let handlers = std::mem::take(&mut state::registry().write().unwrap().handlers);
    drop(handlers);
    types::release_all();
    crate::library::release_all();
    SCRATCH.with(|s| s.borrow_mut().clear());
    state::clear();
    let live = live_objects();
    if live != 0 {
        state::flush();
        eprintln!("nexo: {live} objects were not freed");
    }
}

