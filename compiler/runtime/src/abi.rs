/// `P(a, b)` compiled for a record type: the values are checked against
/// the field types, and the record takes them.
#[no_mangle]
pub unsafe extern "C" fn nx_record_new(t: u64, b: u64, args: *const V, n: u64, span: u32) -> V {
    let args = values(args, n);
    match v(t, b).get() {
        Some(Obj::Type(TypeRef::Record(rt))) if rt.fields.len() == args.len() => {
            let mut fields = Vec::with_capacity(args.len());
            for (i, x) in args.iter().enumerate() {
                let x = Val::adopt(*x).plain();
                let f = &rt.fields[i];
                fields.push(if f.weak { call::field_value(f, x) } else { x });
            }
            Val::new(Obj::Record(Record {
                ty: rt,
                fields: Mut::new(fields),
                birth: std::cell::Cell::new(crate::state::stamp()),
            }))
            .into_raw()
        }
        _ => {
            let r = ret(call::call_value(v(t, b), args, span));
            for x in args {
                release(*x);
            }
            r
        }
    }
}

/// A method call, remembering where the method of a record type is.
#[no_mangle]
pub unsafe extern "C" fn nx_call_method_ic(
    t: u64,
    b: u64,
    name: *const u8,
    len: usize,
    args: *const V,
    nm: *const NameRef,
    n: u64,
    span: u32,
    name_span: u32,
    cache: &std::sync::atomic::AtomicU64,
) -> V {
    let obj = v(t, b);
    let names = names(nm, n);
    if let Some(Obj::Record(r)) = obj.get() {
        let method = match cached(cache, r) {
            Some(i) => Some(r.ty.methods.borrow()[i].1.v()),
            None => {
                let name = text(name, len);
                if r.ty.fields.iter().any(|f| f.name == name) {
                    None
                } else {
                    let methods = r.ty.methods.borrow();
                    let i = methods.iter().position(|(m, _)| m == name);
                    i.map(|i| {
                        remember(cache, r, i);
                        methods[i].1.v()
                    })
                }
            }
        };
        if let Some(m) = method {
            return ret(call::call_method_value(obj, m, values(args, n), &names, span));
        }
    }
    ret(call::call_method(obj, text(name, len), values(args, n), &names, span, name_span))
}

