/// `(*slot).name(args)`: `add` changes the collection in its place.
#[no_mangle]
pub unsafe extern "C" fn nx_call_method_at(
    slot: *mut V,
    name: *const u8,
    len: usize,
    args: *const V,
    nm: *const NameRef,
    n: u64,
    span: u32,
    name_span: u32,
) -> V {
    let name = text(name, len);
    if name == "add" {
        crate::cow::make_unique(slot);
        // `xs.add(x)`, the common case
        if n == 1 && nm.is_null() {
            if let Some(Obj::List(items)) = (*slot).get() {
                let arg = *args;
                if arg.tag != T_OBJ {
                    items.borrow_mut().push(Val::simple(arg.plain()));
                    scratch_clear();
                    return NONE;
                }
            }
        }
    }
    let names = names(nm, n);
    let r = ret(call::call_method(*slot, name, values(args, n), &names, span, name_span));
    scratch_clear();
    r
}

