unsafe fn fields(decls: *const FieldDecl, n: u64, defaults: *const V) -> Vec<FieldInfo> {
    if n == 0 {
        return Vec::new();
    }
    let decls = std::slice::from_raw_parts(decls, n as usize);
    decls
        .iter()
        .enumerate()
        .map(|(i, f)| FieldInfo {
            name: f.name.get().unwrap_or("").to_string(),
            ty: if f.desc.ptr.is_null() { None } else { Some(types::desc(f.desc.ptr, f.desc.len as usize)) },
            optional: f.optional & 1 != 0,
            weak: f.optional & 2 != 0,
            private: f.optional & 4 != 0,
            default: if defaults.is_null() { Val::simple(UNDEF) } else { Val::from(*defaults.add(i)) },
        })
        .collect()
}

