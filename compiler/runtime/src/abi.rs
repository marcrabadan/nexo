#[inline]
fn v(tag: u64, bits: u64) -> V {
    V { tag, bits }
}

/// Give an owned result to the compiled code (NONE when it failed).
#[inline]
fn ret(r: R<Val>) -> V {
    match r {
        Ok(v) => v.into_raw(),
        Err(_) => NONE,
    }
}

unsafe fn text(ptr: *const u8, len: usize) -> &'static str {
    if ptr.is_null() {
        return "";
    }
    std::str::from_utf8_unchecked(std::slice::from_raw_parts(ptr, len))
}

unsafe fn values(ptr: *const V, n: u64) -> &'static [V] {
    if n == 0 {
        return &[];
    }
    std::slice::from_raw_parts(ptr, n as usize)
}

unsafe fn names(ptr: *const NameRef, n: u64) -> std::borrow::Cow<'static, [Option<&'static str>]> {
    static POSITIONAL: [Option<&str>; 16] = [None; 16];
    if ptr.is_null() || n == 0 {
        if n <= 16 {
            return std::borrow::Cow::Borrowed(&POSITIONAL[..n as usize]);
        }
        return std::borrow::Cow::Owned(vec![None; n as usize]);
    }
    std::borrow::Cow::Owned(std::slice::from_raw_parts(ptr, n as usize).iter().map(|r| r.get()).collect())
}

// ------------------------------------------------------------- lifecycle

#[no_mangle]
pub unsafe extern "C" fn nx_init(
    file: *const u8,
    file_len: usize,
    src: *const u8,
    src_len: usize,
    spans: *const SpanRec,
    nspans: u64,
    lang: u32,
    cleanup: extern "C" fn(*mut Tls),
) {
    nexo_diag::set_lang(if lang == 1 { Lang::En } else { Lang::Es });
    if std::env::var("NEXO_LEAKCHECK").is_ok_and(|v| v == "1") {
        enable_leakcheck();
    }
    *CLEANUP.lock().unwrap() = Some(cleanup);
    let spans: &'static [SpanRec] = if nspans == 0 { &[] } else { std::slice::from_raw_parts(spans, nspans as usize) };
    state::init(text(file, file_len), text(src, src_len), spans);
}

/// Releases the program's top-level variables (generated by the compiler).
static CLEANUP: Mutex<Option<extern "C" fn(*mut Tls)>> = Mutex::new(None);

/// The state of this thread, for the compiled code.
#[no_mangle]
pub extern "C" fn nx_tls() -> *mut Tls {
    state::tls()
}

/// Run the program on a thread with a large stack, so that deep recursion
/// reaches the call limit before the end of the stack.
#[no_mangle]
pub extern "C" fn nx_start(entry: extern "C" fn(*mut Tls)) -> ! {
    let handle = std::thread::Builder::new().stack_size(1 << 30).spawn(move || entry(state::tls()));
    match handle {
        Ok(h) => {
            let _ = h.join();
        }
        Err(_) => entry(state::tls()),
    }
    nx_exit(0)
}

