/// `e[i] = x` where `e` is not a place: the change is not seen by anyone
/// (copy-on-write), but the index is still checked.
#[no_mangle]
pub extern "C" fn nx_set_index(ot: u64, ob: u64, it: u64, ib: u64, t: u64, b: u64, span: u32) {
    let o = v(ot, ob);
    if owners(o) <= 1 {
        let _ = coll::set_index(o, v(it, ib), v(t, b), span);
    } else if let Some(copy) = crate::cow::shallow_copy(o) {
        let _ = coll::set_index(copy.v(), v(it, ib), v(t, b), span);
    } else {
        let _ = coll::set_index(o, v(it, ib), v(t, b), span);
    }
}

// ------------------------------------------------------------ places
//
// A change through a place (`xs[i] = v`, `order.items.add(x)`,
// `m[k][j] += 1`): the compiled code asks for a pointer to the place,
// each step making the collection there unique (copy-on-write).

thread_local! {
    /// values of steps that are not stored in a container (see field_slot)
    static SCRATCH: RefCell<Vec<Box<Val>>> = const { RefCell::new(Vec::new()) };
}

fn scratch(v: Val) -> *mut V {
    let mut b = Box::new(v);
    let p = &mut *b as *mut Val as *mut V;
    SCRATCH.with(|s| s.borrow_mut().push(b));
    p
}

fn scratch_clear() {
    let old = SCRATCH.with(|s| {
        let mut s = s.borrow_mut();
        if s.is_empty() {
            Vec::new()
        } else {
            std::mem::take(&mut *s)
        }
    });
    drop(old);
}

#[no_mangle]
pub extern "C" fn nx_scratch_clear() {
    scratch_clear();
}

/// The variable at `slot` is about to be changed: make its collection unique.
#[no_mangle]
pub unsafe extern "C" fn nx_unique_slot(slot: *mut V) {
    crate::cow::make_unique(slot);
}

/// `obj.name` as a place.
#[no_mangle]
pub unsafe extern "C" fn nx_field_slot(ot: u64, ob: u64, name: *const u8, len: usize, span: u32) -> *mut V {
    let mut tmp = Val::none();
    match call::field_slot(v(ot, ob), text(name, len), &mut tmp, span) {
        Ok(Some(p)) => p,
        Ok(None) => scratch(tmp),
        Err(_) => scratch(Val::none()),
    }
}

/// `(*slot)[index]` as a place.
#[no_mangle]
pub unsafe extern "C" fn nx_index_slot(slot: *mut V, it: u64, ib: u64, span: u32) -> *mut V {
    let container = crate::cow::make_unique(slot);
    let forced = match pipe::force(container) {
        Ok(f) => f,
        Err(_) => return scratch(Val::none()),
    };
    let mut tmp = Val::none();
    match coll::element_slot(forced.v(), v(it, ib), &mut tmp, span) {
        Ok(Some(p)) => p,
        Ok(None) => scratch(tmp),
        Err(_) => scratch(Val::none()),
    }
}

