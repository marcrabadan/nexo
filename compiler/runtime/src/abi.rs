#[no_mangle]
pub extern "C" fn nx_index(ot: u64, ob: u64, it: u64, ib: u64, span: u32) -> V {
    // an int index of a map or a list, the common case (D134)
    if it == T_INT {
        match v(ot, ob).get() {
            Some(Obj::Map(m)) => {
                let m = m.borrow();
                let x = m.index.get_int(ib as i64).map(|i| m.entries[*i].1.v()).unwrap_or(NONE);
                retain(x);
                return x;
            }
            Some(Obj::List(items)) => {
                let items = items.borrow();
                if let Some(x) = usize::try_from(ib as i64).ok().and_then(|i| items.get(i)) {
                    let x = x.v();
                    retain(x);
                    return x;
                }
            }
            _ => {}
        }
    }
    ret(coll::get_index(v(ot, ob), v(it, ib), span))
}

/// `e[i] = x` where `e` is not a place: the change is not seen by anyone
/// (copy-on-write), but the index is still checked.
#[no_mangle]
pub extern "C" fn nx_set_index(ot: u64, ob: u64, it: u64, ib: u64, t: u64, b: u64, span: u32) {
    let o = v(ot, ob);
    if owners(o) <= 1 {
        let _ = coll::set_index(o, v(it, ib), v(t, b), span);
    } else if let Some(copy) = crate::cow::shallow_copy(o) {
        let _ = coll::set_index(copy.v(), v(it, ib), v(t, b), span);
    } else {
        let _ = coll::set_index(o, v(it, ib), v(t, b), span);
    }
}

// ------------------------------------------------------------ places
//
// A change through a place (`xs[i] = v`, `order.items.add(x)`,
// `m[k][j] += 1`): the compiled code asks for a pointer to the place,
// each step making the collection there unique (copy-on-write).

thread_local! {
    /// values of steps that are not stored in a container (see field_slot)
    static SCRATCH: RefCell<Vec<Box<Val>>> = const { RefCell::new(Vec::new()) };
}

fn scratch(v: Val) -> *mut V {
    let mut b = Box::new(v);
    let p = &mut *b as *mut Val as *mut V;
    SCRATCH.with(|s| s.borrow_mut().push(b));
    p
}

fn scratch_clear() {
    if SCRATCH.with(|s| s.borrow().is_empty()) {
        return;
    }
    let old = SCRATCH.with(|s| {
        let mut s = s.borrow_mut();
        if s.is_empty() {
            Vec::new()
        } else {
            std::mem::take(&mut *s)
        }
    });
    drop(old);
}

#[no_mangle]
pub extern "C" fn nx_scratch_clear() {
    scratch_clear();
}

/// The variable at `slot` is about to be changed: make its collection unique.
/// `xs.add(x)` on a list that this place alone owns (it was just made
/// unique) and a value that is not lazy: pushed here, 1. Otherwise 0, and
/// the compiled code calls the method as usual (D134).
#[no_mangle]
pub unsafe extern "C" fn nx_list_add(slot: *mut V, t: u64, b: u64) -> u8 {
    let obj = *slot;
    let arg = v(t, b);
    if let Some(Obj::List(items)) = obj.get() {
        // an int onto a list of ints, the most common case (D137)
        if arg.tag == T_INT && owners(obj) <= 1 {
            if let ListItems::Ints(v) = items.borrow_mut() {
                v.push(arg.bits as i64);
                return 1;
            }
        }
        if owners(obj) <= 1 && !matches!(arg.get(), Some(Obj::Lazy(_) | Obj::Grouped(_))) {
            let x = coll::stored_in(obj, Val::from(arg.plain()));
            items.borrow_mut().push(x);
            return 1;
        }
    }
    0
}

/// `list.add(n)` with an int the compiler knows (D178): the common case
/// in a few instructions, anything else through nx_list_add.
#[no_mangle]
pub unsafe extern "C" fn nx_list_add_int(slot: *mut V, n: i64) -> u8 {
    let obj = *slot;
    if obj.tag == T_OBJ && owners(obj) <= 1 {
        if let Some(Obj::List(items)) = obj.get() {
            if let ListItems::Ints(v) = items.borrow_mut() {
                let len = v.len();
                if len < v.capacity() {
                    // SAFETY: within the capacity, and the length counts it
                    v.as_mut_ptr().add(len).write(n);
                    v.set_len(len + 1);
                    return 1;
                }
            }
        }
    }
    list_add_cold(slot, n)
}

#[cold]
#[inline(never)]
unsafe fn list_add_cold(slot: *mut V, n: i64) -> u8 {
    nx_list_add(slot, T_INT, n as u64)
}

