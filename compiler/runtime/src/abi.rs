static TESTS: Mutex<Vec<(String, Val)>> = Mutex::new(Vec::new());

/// A `test` block reached while running the top level of the file.
#[no_mangle]
pub unsafe extern "C" fn nx_test_register(name: *const u8, len: usize, t: u64, b: u64) {
    let name = text(name, len).to_string();
    TESTS.lock().unwrap().push((name, Val::from(v(t, b))));
}

/// Run every registered test, each in its own scope (D54).
#[no_mangle]
pub extern "C" fn nx_run_tests() -> ! {
    let tests: Vec<(String, Val)> = TESTS.lock().unwrap().clone();
    if !tests.is_empty() {
        if !crate::web::serve_in_background() {
            state::report_pending();
            std::process::exit(1);
        }
        nx_test_header();
    }
    for (name, f) in tests {
        crate::library::clear_fakes();
        drop(call::call_value(f.v(), &[], 0));
        crate::library::clear_fakes();
        unsafe { nx_test_result(name.as_ptr(), name.len()) };
    }
    nx_test_finish()
}
