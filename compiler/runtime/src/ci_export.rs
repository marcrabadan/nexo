//! `nexo ci export github|gitlab|azure|jenkins` (D123): the file of each
//! CI service. Follows phase 0's ci_export.py: every step is a job that
//! runs `nexo ci run PIPELINE FILE --step NAME --yes`; what the steps keep
//! travels in `.nexo/ci` between jobs, a step that calls approve() waits
//! for the service's own approval, and the after blocks run when the steps
//! pass or fail.

use crate::ci::Pipeline;

pub const TARGETS: &[&str] = &["github", "gitlab", "azure", "jenkins"];
const INSTALL: &str = "pip install nexo";

type Approvals = [(String, Vec<String>)];

fn header(target: &str, file: &str) -> String {
    format!("Generated by nexo ci export {target} from {file}; do not edit.")
}

fn command(p: &Pipeline, file: &str, step: Option<&str>, after: Option<&str>) -> String {
    match after {
        Some(a) => format!("nexo ci run {} {file} --after {a}", p.name),
        None => format!("nexo ci run {} {file} --step {} --yes", p.name, step.unwrap_or("")),
    }
}

/// A YAML string in single quotes.
fn quote(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

fn approval<'a>(approvals: &'a Approvals, step: &str) -> Option<&'a Vec<String>> {
    approvals.iter().find(|(s, _)| s == step).map(|(_, n)| n)
}

fn has_after(p: &Pipeline, what: &str) -> bool {
    p.after.iter().any(|(w, _)| w == what)
}

fn s(x: &str) -> String {
    x.to_string()
}

/// (path, text) of the file.
pub fn export(target: &str, p: &Pipeline, file: &str, approvals: &Approvals) -> (String, String) {
    match target {
        "github" => github(p, file, approvals),
        "gitlab" => gitlab(p, file, approvals),
        "azure" => azure(p, file, approvals),
        _ => jenkins(p, file, approvals),
    }
}

fn github(p: &Pipeline, file: &str, approvals: &Approvals) -> (String, String) {
    let mut out = vec![format!("# {}", header("github", file)), format!("name: {}", p.name), s("on:")];
    if p.triggers.is_empty() {
        out.push(s("  workflow_dispatch:"));
    }
    for (kind, branch) in &p.triggers {
        if kind == "push" {
            out.push(s("  push:"));
            if let Some(b) = branch {
                out.push(s("    branches:"));
                out.push(format!("      - {}", quote(b)));
            }
        } else {
            out.push(s("  pull_request:"));
        }
    }
    if !p.secrets.is_empty() {
        out.push(s("env:"));
        for sec in &p.secrets {
            out.push(format!("  {sec}: ${{{{ secrets.{sec} }}}}"));
        }
    }
    out.push(s("jobs:"));
    let names: Vec<&str> = p.steps.iter().map(|(n, _)| n.as_str()).collect();
    let job = |jid: &str, needs: &[&str], run: String, extra: Vec<String>| -> Vec<String> {
        let mut lines = vec![format!("  {jid}:"), s("    runs-on: ubuntu-latest")];
        if !needs.is_empty() {
            lines.push(format!("    needs: [{}]", needs.join(", ")));
        }
        lines.extend(extra);
        for l in [
            "    steps:",
            "      - uses: actions/checkout@v4",
            "        with:",
            "          fetch-depth: 0",
            "      - uses: actions/setup-python@v5",
            "        with:",
            "          python-version: '3.12'",
        ] {
            lines.push(s(l));
        }
        lines.push(format!("      - run: {INSTALL}"));
        if !needs.is_empty() {
            for l in ["      - uses: actions/download-artifact@v4", "        with:", "          name: nexo-ci", "          path: .nexo/ci"] {
                lines.push(s(l));
            }
        }
        lines.push(format!("      - run: {run}"));
        lines
    };
    for (i, name) in names.iter().enumerate() {
        let mut extra = Vec::new();
        if let Some(people) = approval(approvals, name) {
            extra.push(format!("    # approve: {}", people.join(", ")));
            extra.push(format!("    environment: {name}"));
        }
        let needs: &[&str] = if i > 0 { &names[i - 1..i] } else { &[] };
        out.extend(job(name, needs, command(p, file, Some(name), None), extra));
        for l in [
            "      - uses: actions/upload-artifact@v4",
            "        if: always()",
            "        with:",
            "          name: nexo-ci",
            "          path: .nexo/ci",
            "          include-hidden-files: true",
            "          overwrite: true",
        ] {
            out.push(s(l));
        }
    }
    for (what, cond) in [("success", "success()"), ("failure", "failure()")] {
        if has_after(p, what) {
            out.extend(job(&format!("after-{what}"), &names, command(p, file, None, Some(what)), vec![format!("    if: {cond}")]));
        }
    }
    (format!(".github/workflows/{}.yml", p.name), out.join("\n") + "\n")
}

fn gitlab(p: &Pipeline, file: &str, approvals: &Approvals) -> (String, String) {
    let names: Vec<&str> = p.steps.iter().map(|(n, _)| n.as_str()).collect();
    let mut stages: Vec<&str> = names.clone();
    if !p.after.is_empty() {
        stages.push("after");
    }
    let mut out = vec![format!("# {}", header("gitlab", file))];
    if !p.secrets.is_empty() {
        out.push(format!("# secrets (CI/CD variables): {}", p.secrets.join(", ")));
    }
    out.push(s("workflow:"));
    out.push(s("  rules:"));
    if p.triggers.is_empty() {
        out.push(s("    - if: $CI_PIPELINE_SOURCE == \"web\""));
    }
    for (kind, branch) in &p.triggers {
        match (kind.as_str(), branch) {
            ("push", Some(b)) => out.push(format!("    - if: $CI_PIPELINE_SOURCE == \"push\" && $CI_COMMIT_BRANCH == \"{b}\"")),
            ("push", None) => out.push(s("    - if: $CI_PIPELINE_SOURCE == \"push\"")),
            _ => out.push(s("    - if: $CI_PIPELINE_SOURCE == \"merge_request_event\"")),
        }
    }
    out.push(s("stages:"));
    for st in &stages {
        out.push(format!("  - {st}"));
    }
    out.push(s("default:"));
    out.push(s("  image: python:3.12"));
    out.push(s("  before_script:"));
    out.push(format!("    - {INSTALL}"));
    for l in ["  artifacts:", "    when: always", "    paths:", "      - .nexo/ci/", "variables:", "  GIT_DEPTH: 0"] {
        out.push(s(l));
    }
    for name in &names {
        out.push(format!("{name}:"));
        out.push(format!("  stage: {name}"));
        if let Some(people) = approval(approvals, name) {
            out.push(format!("  # approve: {}", people.join(", ")));
            out.push(s("  when: manual"));
            out.push(s("  allow_failure: false"));
        }
        out.push(s("  script:"));
        out.push(format!("    - {}", command(p, file, Some(name), None)));
    }
    for (what, when) in [("success", "on_success"), ("failure", "on_failure")] {
        if has_after(p, what) {
            out.push(format!("after-{what}:"));
            out.push(s("  stage: after"));
            out.push(format!("  when: {when}"));
            out.push(s("  script:"));
            out.push(format!("    - {}", command(p, file, None, Some(what))));
        }
    }
    (s(".gitlab-ci.yml"), out.join("\n") + "\n")
}

fn azure(p: &Pipeline, file: &str, approvals: &Approvals) -> (String, String) {
    let mut out = vec![format!("# {}", header("azure", file))];
    let pushes: Vec<&Option<String>> = p.triggers.iter().filter(|(k, _)| k == "push").map(|(_, b)| b).collect();
    if pushes.is_empty() {
        out.push(s("trigger: none"));
    } else {
        out.push(s("trigger:"));
        out.push(s("  branches:"));
        out.push(s("    include:"));
        for b in pushes {
            out.push(format!("      - {}", quote(b.as_deref().unwrap_or("*"))));
        }
    }
    if p.triggers.iter().any(|(k, _)| k == "pull_request") {
        for l in ["pr:", "  branches:", "    include:", "      - '*'"] {
            out.push(s(l));
        }
    } else {
        out.push(s("pr: none"));
    }
    for l in ["pool:", "  vmImage: ubuntu-latest", "stages:"] {
        out.push(s(l));
    }
    let names: Vec<&str> = p.steps.iter().map(|(n, _)| n.as_str()).collect();
    let steps = |run: String, download: &[&str], publish: bool, stage: &str| -> Vec<String> {
        let mut lines: Vec<String> = [
            "          - checkout: self",
            "            fetchDepth: 0",
            "          - task: UsePythonVersion@0",
            "            inputs:",
            "              versionSpec: '3.12'",
        ]
        .iter()
        .map(|l| s(l))
        .collect();
        lines.push(format!("          - script: {INSTALL}"));
        // after a failure, the artifact of the last step that ran wins
        for d in download {
            lines.push(s("          - task: DownloadPipelineArtifact@2"));
            if download.len() > 1 {
                lines.push(s("            continueOnError: true"));
            }
            lines.push(s("            inputs:"));
            lines.push(format!("              artifact: nexo-ci-{d}"));
            lines.push(s("              path: .nexo/ci"));
        }
        lines.push(format!("          - script: {run}"));
        if !p.secrets.is_empty() {
            lines.push(s("            env:"));
            for sec in &p.secrets {
                lines.push(format!("              {sec}: $({sec})"));
            }
        }
        if publish {
            for l in ["          - task: PublishPipelineArtifact@1", "            condition: always()", "            inputs:", "              targetPath: .nexo/ci"] {
                lines.push(s(l));
            }
            lines.push(format!("              artifact: nexo-ci-{stage}"));
        }
        lines
    };
    for (i, name) in names.iter().enumerate() {
        out.push(format!("  - stage: {name}"));
        if i > 0 {
            out.push(format!("    dependsOn: {}", names[i - 1]));
        }
        out.push(s("    jobs:"));
        let people = approval(approvals, name);
        if let Some(people) = people {
            for l in ["      - job: approve", "        pool: server", "        steps:", "          - task: ManualValidation@0", "            inputs:"] {
                out.push(s(l));
            }
            out.push(format!("              notifyUsers: {}", quote(&people.join(", "))));
            out.push(format!("              instructions: {}", quote(&format!("Approve the step {name}"))));
        }
        out.push(format!("      - job: {name}"));
        if people.is_some() {
            out.push(s("        dependsOn: approve"));
        }
        out.push(s("        steps:"));
        let download: &[&str] = if i > 0 { &names[i - 1..i] } else { &[] };
        out.extend(steps(command(p, file, Some(name), None), download, true, name));
    }
    for (what, cond) in [("success", "succeeded()"), ("failure", "failed()")] {
        if has_after(p, what) {
            out.push(format!("  - stage: after_{what}"));
            out.push(s("    dependsOn:"));
            for n in &names {
                out.push(format!("      - {n}"));
            }
            out.push(format!("    condition: {cond}"));
            out.push(s("    jobs:"));
            out.push(format!("      - job: after_{what}"));
            out.push(s("        steps:"));
            let download: &[&str] = if what == "failure" { &names } else { &names[names.len() - 1..] };
            out.extend(steps(command(p, file, None, Some(what)), download, false, ""));
        }
    }
    (s("azure-pipelines.yml"), out.join("\n") + "\n")
}

fn groovy(text: &str) -> String {
    format!("'{}'", text.replace('\\', "\\\\").replace('\'', "\\'"))
}

fn jenkins(p: &Pipeline, file: &str, approvals: &Approvals) -> (String, String) {
    let mut conds = Vec::new();
    for (kind, branch) in &p.triggers {
        match (kind.as_str(), branch) {
            ("push", Some(b)) => conds.push(format!("allOf {{ not {{ changeRequest() }}; branch {} }}", groovy(b))),
            ("push", None) => conds.push(s("not { changeRequest() }")),
            _ => conds.push(s("changeRequest()")),
        }
    }
    let mut out = vec![format!("// {}", header("jenkins", file)), s("pipeline {"), s("    agent any")];
    if !p.secrets.is_empty() {
        out.push(s("    environment {"));
        for sec in &p.secrets {
            out.push(format!("        {sec} = credentials({})", groovy(sec)));
        }
        out.push(s("    }"));
    }
    out.push(s("    stages {"));
    out.push(s("        stage('setup') {"));
    out.push(format!("            steps {{ sh {} }}", groovy(INSTALL)));
    out.push(s("        }"));
    for (name, _) in &p.steps {
        out.push(format!("        stage({}) {{", groovy(name)));
        if !conds.is_empty() {
            out.push(format!("            when {{ anyOf {{ {} }} }}", conds.join("; ")));
        }
        if let Some(people) = approval(approvals, name) {
            out.push(format!(
                "            input {{ message {}; submitter {} }}",
                groovy(&format!("Approve the step {name}")),
                groovy(&people.join(","))
            ));
        }
        out.push(format!("            steps {{ sh {} }}", groovy(&command(p, file, Some(name), None))));
        out.push(s("        }"));
    }
    out.push(s("    }"));
    if !p.after.is_empty() {
        out.push(s("    post {"));
        for what in ["success", "failure"] {
            if has_after(p, what) {
                out.push(format!("        {what} {{ sh {} }}", groovy(&command(p, file, None, Some(what)))));
            }
        }
        out.push(s("    }"));
    }
    out.push(s("}"));
    (s("Jenkinsfile"), out.join("\n") + "\n")
}
